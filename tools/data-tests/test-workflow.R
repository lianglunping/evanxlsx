test_that("installed practical workflow preserves measurements, IDs, and missingness", {
  e <- new.env(parent = globalenv())
  script <- system.file("examples", "workflow.R", package = "evanxlsx")
  expect_true(file.exists(script))
  sys.source(script, envir = e)
  old <- options(tidypolars_unknown_args = "warn", tidypolars_fallback_to_r = TRUE)
  on.exit(options(old), add = TRUE)
  before <- options()[names(old)]
  folder <- file.path(Sys.getenv("EVANXLSX_DATA_OUT"), "workflow")
  result <- e$evanxlsx_workflow(folder)
  expect_identical(options()[names(old)], before)
  expect_identical(names(result$sheets), c("clean", "long", "wide", "summary", "flagged"))
  expect_identical(readRDS(file.path(folder, "raw.rds")), result$raw)
  expect_equal(nrow(result$raw), 13L)
  expect_true(is.nan(result$raw$weight[12]))
  materialize <- function(x) if (inherits(x,"polars_lazy_frame")) as.data.frame(x$collect()) else as.data.frame(x)
  clean <- materialize(result$sheets$clean)
  expect_equal(nrow(clean), 12L)
  expect_identical(clean$Sample_ID, sprintf("%04d",1:12))
  expect_identical(clean$Position, sprintf("%05d",1:12))
  expect_identical(clean$batch, rep(c("Batch_A","Batch_B"), each=6))
  expect_true(all(clean$note[seq(3,12,3)] == "NA"))
  expect_true(all(clean$note[seq(2,11,3)] == "Unknown / 未记录"))
  expect_identical(clean$height, result$raw$height[1:12])
  expect_true(is.na(clean$weight[12]))
  expect_false(is.nan(clean$weight[12]))
  expect_equal(clean$weight[1:11], result$raw$weight[1:11])
  long <- materialize(result$sheets$long)
  expect_equal(nrow(long),24L)
  expect_equal(sum(is.na(long$value)),2L)
  expect_false(anyDuplicated(long[c("Sample_ID","trait")]) > 0L)
  wide <- materialize(result$sheets$wide)
  expect_identical(wide$Sample_ID,clean$Sample_ID)
  expect_equal(wide$height,clean$height)
  expect_equal(wide$weight,clean$weight)
  summary <- materialize(result$sheets$summary)
  expect_identical(summary$treatment,c("A","B"))
  for (g in c("A","B")) for (col in c("height","weight")) {
    v <- clean[[col]][clean$treatment==g]
    v <- v[is.finite(v)]
    got <- summary[summary$treatment==g,]
    expect_equal(got[[paste0(col,"__n_total")]],6)
    expect_equal(got[[paste0(col,"__n_valid")]],length(v))
    expect_equal(got[[paste0(col,"__mean")]],mean(v),tolerance=1e-12)
    expect_equal(got[[paste0(col,"__sd")]],stats::sd(v),tolerance=1e-12)
  }
  flagged <- materialize(result$sheets$flagged)
  expect_equal(nrow(flagged),24L)
  expect_equal(sum(flagged$iqr_outlier,na.rm=TRUE),1)
  expect_identical(flagged$Sample_ID[which(flagged$iqr_outlier)],"0006")
  expect_identical(flagged$trait[which(flagged$iqr_outlier)],"height")
  expect_equal(sum(is.na(flagged$iqr_outlier)),2L)
  expect_true(all(flagged$iqr_reason[is.na(flagged$value)]=="missing"))
  expect_true(file.exists(result$path))
  expect_equal(nrow(openxlsx2::read_xlsx(result$path,sheet="long",skip_empty_rows=FALSE)),24L)
  expect_match(paste(readLines(file.path(folder,"summary_plan.txt")),collapse="\n"),"PARQUET",ignore.case=TRUE)
  original <- tools::md5sum(result$path)
  expect_error(e$evanxlsx_workflow(folder),"new output directory")
  expect_identical(tools::md5sum(result$path),original)
})
